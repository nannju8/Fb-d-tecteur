import { and, eq, isNull } from "drizzle-orm";
import { db } from "@/db";
import { accessSessions, collectRuns, clips } from "@/db/schema";
import { jsonError, readJson } from "@/lib/api";
import { GUARDRAILS } from "@/lib/guardrails";
import { getActiveSession, logEvent } from "@/lib/vault";

export const dynamic = "force-dynamic";

type ConnectBody = {
  accountLabel?: string;
  cUserId?: string;
};

export async function POST(request: Request) {
  const body = (await readJson<ConnectBody>(request)) ?? {};
  const rawCookie = (body.cUserId ?? "").trim();

  // In the Android build this is the `c_user` cookie read from the locked
  // WebView. Here the value is supplied by the gate form or generated by the
  // demo button; it is never forwarded to Facebook.
  const cUserId =
    rawCookie || String(Math.floor(1e9 + Math.random() * 8_999_999_999));
  if (!/^\d{5,20}$/.test(cUserId)) {
    return jsonError(
      "La valeur c_user doit être un identifiant numérique (5 à 20 chiffres).",
      400,
    );
  }

  const label = (body.accountLabel ?? "").trim().slice(0, 48) || "Session personnelle";

  // Single active session: revoking the previous one is explicit, not silent.
  await db
    .update(accessSessions)
    .set({ revokedAt: new Date(), lockReason: "remplacée par une nouvelle session" })
    .where(isNull(accessSessions.revokedAt));

  const [session] = await db
    .insert(accessSessions)
    .values({
      accountLabel: label,
      cUserId,
      scope: GUARDRAILS.allowedDomains.join(","),
    })
    .returning();

  await logEvent({
    kind: "session_connected",
    message: `Session liée (c_user ${cUserId.slice(0, 2)}••••${cUserId.slice(-2)}), navigation limitée à ${GUARDRAILS.allowedDomains.join(" / ")}.`,
  });

  return Response.json({ session: { ...session, cUserId } }, { status: 201 });
}

export async function DELETE() {
  const session = await getActiveSession();
  if (!session) {
    return jsonError("Aucune session active.", 409);
  }

  await db
    .update(accessSessions)
    .set({ revokedAt: new Date(), lockReason: "verrouillage manuel" })
    .where(and(eq(accessSessions.id, session.id), isNull(accessSessions.revokedAt)));

  const running = await db
    .select()
    .from(collectRuns)
    .where(eq(collectRuns.status, "running"));

  for (const run of running) {
    await db
      .update(collectRuns)
      .set({
        status: "aborted",
        abortReason: "Session verrouillée",
        finishedAt: new Date(),
      })
      .where(eq(collectRuns.id, run.id));
    await db
      .update(clips)
      .set({ status: "aborted", failReason: "Session verrouillée", updatedAt: new Date() })
      .where(and(eq(clips.runId, run.id), eq(clips.status, "queued")));
  }

  await logEvent({
    kind: "session_locked",
    message: "Coffre verrouillé. Les téléchargements en cours ont été interrompus.",
  });

  return Response.json({ ok: true });
}
